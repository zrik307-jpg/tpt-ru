#!/usr/bin/env python3
# Generates src/common/TranslationsRu.cpp from translations/ru.tsv
import sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def esc(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
rows = []
for line in open(os.path.join(root, 'translations', 'ru.tsv'), encoding='utf8'):
    line = line.rstrip('\n')
    if not line or line.startswith('#'):
        continue
    en, ru = line.split('\t', 1)
    rows.append((en, ru))
with open(os.path.join(root, 'src', 'common', 'TranslationsRu.cpp'), 'w', encoding='utf8') as f:
    f.write('// Generated by tools/gen_translations.py - do not edit\n#include "Translate.h"\n')
    f.write('const TranslationEntry translationTable[] = {\n')
    for en, ru in rows:
        f.write('\t{ %s, %s },\n' % (esc(en), esc(ru)))
    f.write('};\nconst unsigned translationTableSize = %d;\n' % len(rows))
    names = []
    for line in open(os.path.join(root, 'translations', 'names_ru.tsv'), encoding='utf8'):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        names.append(tuple(line.split('\t', 1)))
    f.write('const TranslationEntry toolNameTable[] = {\n')
    for en, ru in names:
        f.write('\t{ %s, %s },\n' % (esc(en), esc(ru)))
    f.write('};\nconst unsigned toolNameTableSize = %d;\n' % len(names))
print(len(rows), 'entries')
